// Waterfall palette parity with the RF Track workbench (P0 stage 3.3).
//
// The workbench is a second, build-free frontend that paints the same waterfall, but
// `web/` (Vite + TypeScript) and `rftrack/frontend/workbench/` (plain ESM) cannot import
// each other — so each side interpolates its own 256-entry table. This is the `web/` half
// of the bargain: it runs the real `seqLut()` against the baseline checked into
// `rftrack/frontend/workbench/vendor/waterfall-lut.json`. The other half is
// `rftrack/frontend/workbench/test/waterfall-lut.test.mjs`.
//
// The baseline is regenerated by `rftrack/tools/make_waterfall_lut.mjs`, which calls this
// same `seqLut()` — so a mismatch here means the shipped numbers are stale, and the fix is
// to re-run the generator, not to relax the comparison.
//
// One thing deliberately absent: reading `--seq-*` out of `src/styles.css`. Vitest stubs CSS
// imports (a `?raw` import of a `.css` file resolves to an empty string under the default
// `css: false`), and switching that on would change how every other test in `web/` loads.
// The "did someone edit a colour stop and regenerate the baseline" check lives on the
// workbench side instead, which reads the CSS straight off disk.

import { afterEach, describe, expect, it } from "vitest";

import baselineRaw from "../../../rftrack/frontend/workbench/vendor/waterfall-lut.json?raw";
import { invalidateTheme, seqLut } from "./canvas";

type BaselineTheme = { selector: string; stops: string[]; lut: number[] };
type Baseline = { entries: number; channels: number; themes: Record<string, BaselineTheme> };

const baseline = JSON.parse(baselineRaw) as Baseline;

// The globals `theme()` touches, in the loosest shapes that still type-check: `web/` runs in
// a browser, this test runs in vitest's node environment.
type Globals = {
  document?: { documentElement: unknown };
  getComputedStyle?: (element: unknown) => { getPropertyValue(name: string): string };
};
const global = globalThis as unknown as Globals;
const saved = { document: global.document, getComputedStyle: global.getComputedStyle };

afterEach(() => {
  if (saved.document === undefined) delete global.document;
  else global.document = saved.document;
  if (saved.getComputedStyle === undefined) delete global.getComputedStyle;
  else global.getComputedStyle = saved.getComputedStyle;
  invalidateTheme();
});

/** Point `theme()` at one theme's stops, the way the page would after setting `data-theme`. */
function useStops(stops: string[]) {
  global.document = { documentElement: {} };
  global.getComputedStyle = () => ({
    getPropertyValue: (name: string) => {
      const j = /^--seq-([0-6])$/.exec(name);
      return j ? stops[Number(j[1])] : "";
    },
  });
  invalidateTheme();
}

const hexToRgb = (hex: string) => [
  parseInt(hex.slice(1, 3), 16),
  parseInt(hex.slice(3, 5), 16),
  parseInt(hex.slice(5, 7), 16),
];

describe("waterfall LUT parity with the workbench baseline", () => {
  it("covers both themes the workbench can paint", () => {
    expect(Object.keys(baseline.themes).sort()).toEqual(["dark", "light"]);
    expect(baseline.entries).toBe(256);
    expect(baseline.channels).toBe(3);
  });

  for (const name of Object.keys(baseline.themes).sort()) {
    const theme = baseline.themes[name];

    it(`${name}: seqLut() matches the baseline byte for byte`, () => {
      useStops(theme.stops);
      const lut = seqLut();
      expect(lut).toBeInstanceOf(Uint8ClampedArray);
      expect(lut.length).toBe(baseline.entries * baseline.channels);

      const mismatched: string[] = [];
      for (let j = 0; j < baseline.entries; j++) {
        const mine = [lut[j * 3], lut[j * 3 + 1], lut[j * 3 + 2]];
        const theirs = theme.lut.slice(j * 3, j * 3 + 3);
        if (mine.some((v, c) => v !== theirs[c])) mismatched.push(`${j}: baseline ${theirs} vs web ${mine}`);
      }
      expect(mismatched, `${mismatched.length} of 256 entries differ (first 5: ${mismatched.slice(0, 5).join(" | ")})`).toEqual([]);
    });

    it(`${name}: the ends of the ramp are the end stops themselves`, () => {
      useStops(theme.stops);
      const lut = seqLut();
      const first = theme.stops[0];
      const last = theme.stops[theme.stops.length - 1];
      expect([lut[0], lut[1], lut[2]]).toEqual(hexToRgb(first));
      const end = lut.length - 3;
      expect([lut[end], lut[end + 1], lut[end + 2]]).toEqual(hexToRgb(last));
    });
  }
});
